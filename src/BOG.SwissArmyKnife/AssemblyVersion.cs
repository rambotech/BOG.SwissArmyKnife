using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using System;
using System.Collections.Generic;
using System.ComponentModel.Design;
using System.IO;
using System.Reflection;
using System.Text;

namespace BOG.SwissArmyKnife
{
	[JsonObject(MemberSerialization = MemberSerialization.OptIn)]
	public class AssemblyVersion
	{
		/// <summary>
		/// The default format used for ToString()
		/// </summary>
		public const string DateFormatStringDefault =
			// "{0:dddd MMMM dd, yyyy} at {0:hh:mm tt}";
			"{0:f}";

		/// <summary>
		/// Defines the source the assembly has to the executing application
		/// Use for ToJson() and ToString() output
		/// </summary>
		public enum AssemblySource : int
		{
			/// <summary>
			/// Default value: only changed if instantion used is: public AssemblyVersion(AssemblySource source)
			/// </summary>
			Unknown = 0,
			/// <summary>
			/// The entry point of the application (exe/dll)
			/// </summary>
			Entry = 1,
			/// <summary>
			/// The parent assembly of the executing application (exe/dll)
			/// </summary>
			Calling = 2,
			/// <summary>
			/// The the executing application (this dll)
			/// </summary>
			Executing = 3
		}

		/// <summary>
		/// What relationship/source this assembly has to the application.
		/// </summary>
		[JsonProperty(PropertyName = "AssemblySource", Required = Required.Always)]
		public AssemblySource Source { get; private set; } = AssemblySource.Unknown; //default

		/// <summary>
		/// The full file name with path
		/// </summary>
		[JsonProperty(PropertyName = "Filename", Required = Required.Always)]
		public string FullFilename { get; private set; } = string.Empty;

		/// <summary>
		/// The file name with no path information
		/// </summary>
		[JsonProperty(PropertyName = "Filename", Required = Required.Always)]
		public string Filename { get; private set; } = string.Empty;

		/// <summary>
		/// The file name with no path information or extension
		/// </summary>
		[JsonProperty(PropertyName = "Name", Required = Required.Always)]
		public string Name { get; private set; } = string.Empty;

		/// <summary>
		/// The version number of the assembly
		/// </summary>
		[JsonProperty(PropertyName = "Version", Required = Required.Always)]
		public string Version { get; private set; } = string.Empty;

		/// <summary>
		/// The date the assembly was generated by the compiler.
		/// </summary>
		[JsonProperty(PropertyName = "BuildDate", Required = Required.Always)]
		public DateTime BuildDate { get; private set; } = DateTime.MaxValue;

		/// <summary>
		/// Get info for the entry assembly: this is the main application start (exe in Windows; dll for other)
		/// </summary>
		public AssemblyVersion()
		{
			Source = AssemblySource.Entry;
			Initialize(Assembly.GetEntryAssembly());
		}

		/// <summary>
		/// Get info for an assembly specified by type.
		/// </summary>
		public AssemblyVersion(Type typeObj)
		{
			Initialize(Assembly.GetAssembly(typeObj));
		}

		/// <summary>
		/// Get info for the specified assembly from the 3 common methods in System.Reflection.
		/// </summary>
		public AssemblyVersion(AssemblySource source)
		{
			Source = source;

			switch (source)
			{
				case AssemblySource.Entry:
					Initialize(Assembly.GetEntryAssembly());
					break;
				case AssemblySource.Calling:
					Initialize(Assembly.GetCallingAssembly());
					break;
				case AssemblySource.Executing:
					Initialize(Assembly.GetExecutingAssembly());
					break;
				default:
				case AssemblySource.Unknown:
					throw new ArgumentException(
						$"{source} is a default marker-only, which is not valid for this instantiaton: use AssemblyVersion(Type typeObj)");
			}
		}

		/// Get info for an assembly specified by name.		
		public AssemblyVersion(string assemblyFileName)
		{
			Initialize(Assembly.LoadFile(assemblyFileName));
		}

		private void Initialize(Assembly assembly)
		{
			var av = assembly.GetName();
			Name = av.Name;
			Filename = assembly.Location;
			Version = av.Version.ToString();
			BuildDate = File.GetCreationTime(Filename);
		}

		/// <summary>
		/// Generate single line string summary. Date uses default format.
		/// </summary>
		/// <returns></returns>
		public override string ToString()
		{
			return ToString(DateFormatStringDefault);
		}

		/// <summary>
		/// Generate single line string summary using a user-provided format string
		/// </summary>
		/// <param name="formatStr">Provide format value as in these examples:
		///		#1: "{0:g}"
		///		#2: "{0:dddd MMMM dd, yyyy} at {0:hh:mm tt}"
		///		<list type="bullet">
		///		<item>"{0:g}"</item>
		///		<item>"{0:dddd MMMM dd, yyyy} at {0:hh:mm tt}"</item>
		///		</list>
		///		example #2 is using the same DateTime (arg {0}) to create a complex date/time format.
		/// </param>
		/// <returns>string with Banner content</returns>
		public string ToString(string formatStr)
		{
			var result = string.Format(formatStr,
				Path.GetFileName(Filename),
				Version,
				string.Format(formatStr, BuildDate),
				Source
			);
			return result;
		}

		/// <summary>
		/// Generate Json object for REST
		/// </summary>
		/// <param name="includeSource">Include the source (Undefined, Entry ... aka the role)</param>
		/// <param name="dateFormatStr">see description in ToString(string formatStr)</param>
		/// <returns></returns>
		public JObject ToJson(bool includeSource, string dateFormatStr)
		{
			JObject result;
			switch (includeSource)
			{
				case true:
					result = new JObject()
					{
						{ "file", Path.GetFileName(Filename) },
						{ "name", Name },
						{ "version", Version },
						{ "built", string.Format(dateFormatStr,BuildDate) },
						{ "source", Source.ToString() }
					};
					break;
				default:
					result = new JObject
					{
						{ "file", Path.GetFileName(Filename) },
						{ "name", Name },
						{ "version", Version },
						{ "built", string.Format(dateFormatStr,BuildDate) }
					};
					break;
			}
			return result;
		}

		/// <summary>
		/// Generate Json object for REST
		/// </summary>
		/// <param name="dateFormatStr">see description in ToString(string formatStr)</param>
		/// <returns>JSON KV object</returns>
		public JObject ToJson(string dateFormatStr)
		{
			return ToJson(false, dateFormatStr);
		}


		/// <summary>
		/// Generate Json object for REST
		/// </summary>
		/// <param name="includeSource">Include the source (Undefined, Entry ... aka the role)</param>
		/// /// <returns>JSON KV object</returns>
		public JObject ToJson(bool includeSource)
		{
			return ToJson(includeSource, DateFormatStringDefault);
		}

		/// <summary>
		/// Generate Json object for REST
		/// </summary>
		/// <returns>JSON KV object</returns>
		public JObject ToJson()
		{
			return ToJson(false, DateFormatStringDefault);
		}
	}
}
